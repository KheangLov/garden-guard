export type SpriteName = keyof typeof SPRITES

/** A sprite as standalone SVG markup (for the interface: cards, story portraits, the map). */
export function spriteSvg(name: SpriteName, className = ''): string {
  const def: SpriteDef = SPRITES[name]
  const parts = def.ops.map((op) => {
    let shape: string
    let style: Style
    switch (op[0]) {
      case 'p':
        shape = `<path d="${op[1]}"`
        style = op.slice(2) as Style
        break
      case 'c':
        shape = `<circle cx="${op[1]}" cy="${op[2]}" r="${op[3]}"`
        style = op.slice(4) as Style
        break
      case 'e':
        shape = `<ellipse cx="${op[1]}" cy="${op[2]}" rx="${op[3]}" ry="${op[4]}"`
        style = op.slice(5) as Style
        break
      case 'r':
        shape = `<rect x="${op[1]}" y="${op[2]}" width="${op[3]}" height="${op[4]}" rx="${op[5]}"`
        style = op.slice(6) as Style
        break
    }
    const [fill, stroke, lw, alpha] = style
    return `${shape} fill="${fill ?? 'none'}"${stroke ? ` stroke="${stroke}" stroke-width="${lw ?? 1}"` : ''}${alpha != null ? ` opacity="${alpha}"` : ''}/>`
  })
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 -4 ${def.vw} ${def.vh + 4}" class="${className}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${parts.join('')}</svg>`
}
